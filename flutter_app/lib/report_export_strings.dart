/// Fixed, source-grounded PDF copy. Report labels, values, units, reference
/// text and clinical narratives are never translated by this catalog.
class ReportExportStrings {
  ReportExportStrings(String language) : code = _code(language);

  final String code;

  static String _code(String language) => switch (language.toLowerCase()) {
        'hi' || 'hindi' || 'हिंदी' => 'hi',
        'es' || 'spanish' || 'español' => 'es',
        'zh' || 'zh-cn' || 'mandarin' || 'chinese' || '中文' => 'zh',
        _ => 'en',
      };

  String text(String key) => _copy[code]![key] ?? _copy['en']![key]!;

  String sourcePage(dynamic page) =>
      text('sourcePage').replaceAll('{page}', '$page');

  String pageCount(int page, int count) => text('pageCount')
      .replaceAll('{page}', '$page')
      .replaceAll('{count}', '$count');

  String status(dynamic value) => text(switch (value) {
        'normal' => 'normal',
        'high' => 'high',
        'low' => 'low',
        'abnormal' => 'abnormal',
        'critical' => 'critical',
        _ => 'unknown',
      });

  String coverage(Map quality) => text('coverage')
      .replaceAll('{measurements}', '${quality['eligible_count'] ?? 0}')
      .replaceAll('{notes}', '${quality['eligible_narrative_count'] ?? 0}')
      .replaceAll('{review}', '${quality['needs_review_count'] ?? 0}')
      .replaceAll(
          '{unresolved}', '${quality['unresolved_result_regions'] ?? 0}');

  String displayDate(String value) {
    final date = DateTime.tryParse(value);
    if (date == null) return value;
    if (code == 'zh') return '${date.year}年${date.month}月${date.day}日';
    final month = _months[code]![date.month - 1];
    if (code == 'es') return '${date.day} de $month de ${date.year}';
    return '${date.day} $month ${date.year}';
  }

